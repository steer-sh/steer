def interpreter_targets(tokens, bodies):
    """Return the README.md paths named in literals of interpreter code that writes files."""
    if not tokens or os.path.basename(tokens[0]) not in INTERPRETERS:
        return []
    code = " ".join(tokens[1:]) + "\n" + bodies
    if not INTERPRETER_WRITE.search(code):
        return []
    return README_LITERAL.findall(code)


def bash_violation(command, cwd):
    """Return whether a shell command changes the root README.md."""
    text, bodies = split_heredocs(command)
    directory = cwd
    for raw in segments(text):
        tokens = strip_prefix(raw)
        if not tokens:
            continue
        if tokens[0] == "cd" and len(tokens) > 1:
            directory = os.path.join(directory, os.path.expanduser(tokens[1]))
            continue
        if os.path.basename(tokens[0]) in SHELLS and "-c" in tokens[1:-1]:
            if bash_violation(tokens[tokens.index("-c", 1) + 1], directory):
                return True
        if any(is_root_readme(p, directory) for p in written_paths(tokens, directory)):
            return True
        if any(is_root_readme(p, directory) for p in interpreter_targets(tokens, bodies)):
            return True
    return False


