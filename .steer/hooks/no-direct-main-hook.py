SEPARATORS = set(";&|()")
WRAPPERS = {"sudo", "env", "time", "nohup", "exec", "command"}
GIT_VALUE_FLAGS = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
PUSH_VALUE_FLAGS = {"--repo", "-o", "--push-option", "--receive-pack", "--exec"}
INIT_VALUE_FLAGS = {"-b", "--initial-branch", "--template", "--separate-git-dir",
                    "--object-format", "--ref-format"}
HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")
ASSIGNMENT = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)=(.*)", re.DOTALL)
VARIABLE = re.compile(r"\$(?:\{([A-Za-z_][A-Za-z0-9_]*)\}|([A-Za-z_][A-Za-z0-9_]*))")
# A command substitution that creates a new directory under the temporary directory.
MKTEMP_DIR = re.compile(r"\$\(\s*mktemp\s+(?:-d|-d\s+-t\s+[\w.-]+|-dt\s+[\w.-]+)\s*\)")


def strip_heredocs(command):
    """Return command without heredoc bodies, which are data."""
    kept = []
    closing = []
    for line in command.split("\n"):
        if closing:
            if line.strip() == closing[0]:
                closing.pop(0)
            continue
        kept.append(line)
        closing.extend(match.group(2) for match in HEREDOC.finditer(line))
    return "\n".join(kept)


def segments(command):
    """Return (tokens, following separator, preceding separators) per command in a shell string.

    Returns [] if the string does not parse.
    """
    text = strip_heredocs(command).replace("\n", " ; ")
    lexer = shlex.shlex(text, posix=True, punctuation_chars=";&|()")
    lexer.whitespace_split = True
    try:
        tokens = list(lexer)
    except ValueError:
        return []
    result = []
    current = []
    before = ""
    for token in tokens:
        if set(token) <= SEPARATORS:
            if current:
                result.append((current, token, before))
                before = token
            else:
                before += token
            current = []
        else:
            current.append(token)
    if current:
        result.append((current, "", before))
    return result


def strip_prefix(tokens):
    """Drop leading VAR=value assignments and command wrappers."""
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token in WRAPPERS or re.match(r"[A-Za-z_][A-Za-z0-9_]*=", token):
            index += 1
        else:
            break
    return tokens[index:]


def git_files(start):
    """Return the checkout's HEAD path and config path, or None outside a repository."""
    path = os.path.abspath(start)
    while True:
        dot_git = os.path.join(path, ".git")
        if os.path.isdir(dot_git):
            return os.path.join(dot_git, "HEAD"), os.path.join(dot_git, "config")
        if os.path.isfile(dot_git):
            with open(dot_git, encoding="utf-8") as handle:
                git_dir = handle.read().strip().removeprefix("gitdir:").strip()
            git_dir = os.path.normpath(os.path.join(path, git_dir))
            common = git_dir
            commondir = os.path.join(git_dir, "commondir")
            if os.path.isfile(commondir):
                with open(commondir, encoding="utf-8") as handle:
                    common = os.path.normpath(os.path.join(git_dir, handle.read().strip()))
            return os.path.join(git_dir, "HEAD"), os.path.join(common, "config")
        parent = os.path.dirname(path)
        if parent == path:
            return None
        path = parent


def current_branch(directory):
    """Return the branch checked out at directory in this repository, or "" if none applies."""
    try:
        files = git_files(directory)
        if files is None:
            return ""
        with open(files[1], encoding="utf-8") as handle:
            if not REPOSITORY.search(handle.read()):
                return ""
        with open(files[0], encoding="utf-8") as handle:
            head = handle.read().strip()
    except OSError:
        return ""
    return head.removeprefix("ref: refs/heads/") if head.startswith("ref: refs/heads/") else ""


def is_this_repository(directory):
    """Return whether directory is a checkout of this repository, on any branch or none."""
    try:
        files = git_files(directory)
        if files is None:
            return False
        with open(files[1], encoding="utf-8") as handle:
            return bool(REPOSITORY.search(handle.read()))
    except OSError:
        return False


def parse_git(tokens, directory):
    """Return the working directory, the subcommand and its arguments of a git invocation."""
    index = 1
    while index < len(tokens) and tokens[index].startswith("-"):
        flag = tokens[index]
        if flag == "-C" and index + 1 < len(tokens):
            directory = os.path.join(directory, os.path.expanduser(tokens[index + 1]))
        index += 2 if flag in GIT_VALUE_FLAGS else 1
    if index >= len(tokens):
        return directory, "", []
    return directory, tokens[index], tokens[index + 1:]


def head_key(directory):
    """Return a key shared by every directory of one checkout."""
    try:
        files = git_files(directory)
    except OSError:
        files = None
    return files[0] if files else directory


def switched_branch(subcommand, arguments):
    """Return the branch a switch or checkout moves to, or "" if it moves to none.

    A checkout argument can name a file, so only -b, -B or main count as a move.
    """
    if "--" in arguments:
        return ""
    names = [argument for argument in arguments if not argument.startswith("-")]
    if not names:
        return ""
    creates = "-b" in arguments or "-B" in arguments
    if subcommand == "checkout" and not creates and names[0] != PROTECTED:
        return ""
    return names[0]


def initialized_directory(arguments, directory):
    """Return the directory a git init creates a repository in, or "" if it exists already."""
    index = 0
    while index < len(arguments):
        argument = arguments[index]
        if not argument.startswith("-"):
            directory = os.path.join(directory, os.path.expanduser(argument))
            break
        index += 2 if argument in INIT_VALUE_FLAGS else 1
    directory = os.path.normpath(directory)
    return "" if os.path.exists(directory) else directory


def inside(directory, roots):
    """Return whether directory is one of roots or below one."""
    return any(directory == root or directory.startswith(root + os.sep) for root in roots)


def push_targets_main(arguments, branch):
    """Return whether a push with these arguments updates main."""
    positional = []
    index = 0
    tags_only = False
    remote_in_flag = False
    while index < len(arguments):
        argument = arguments[index]
        if argument in ("--all", "--mirror", "--branches"):
            return True
        if argument == "--repo" or argument.startswith("--repo="):
            remote_in_flag = True
        if argument == "--tags":
            tags_only = True
        if argument.startswith("-"):
            index += 2 if argument in PUSH_VALUE_FLAGS else 1
            continue
        positional.append(argument)
        index += 1
    refspecs = positional if remote_in_flag else positional[1:]
    if not refspecs:
        return branch == PROTECTED and not tags_only
    for refspec in refspecs:
        refspec = refspec.lstrip("+")
        source, _, destination = refspec.rpartition(":")
        if not source and ":" not in refspec:
            destination = refspec
        if destination == "HEAD":
            destination = branch
        if destination.removeprefix("refs/heads/") == PROTECTED:
            return True
    return False


def expand(word, variables):
    """Return word with each variable in variables replaced by its value; others stay literal."""
    return VARIABLE.sub(lambda match: variables.get(match.group(1) or match.group(2), match.group(0)), word)


def record_assignments(words, variables, certain, together):
    """Bind each NAME=value in words whose value expands to one literal word, and unbind the rest.

    An assignment that may not run, or runs in a subshell, is not certain and unbinds its name.
    When together, as for export, every value expands against the bindings before any is made.
    """
    before = dict(variables)
    for word in words:
        name, value = ASSIGNMENT.match(word).groups()
        value = expand(value, before if together else variables)
        if not certain or re.search(r"[$`\s*?\[]", value):
            variables.pop(name, None)
        else:
            variables[name] = value


def single_quoted_dollar(text):
    """Return whether a $ sits inside single quotes, where the shell does not expand it."""
    quote = ""
    escaped = False
    for char in text:
        if escaped:
            escaped = False
        elif quote == "'":
            if char == "'":
                quote = ""
            elif char == "$":
                return True
        elif char == "\\":
            escaped = True
        elif quote == '"':
            if char == '"':
                quote = ""
        elif char in "'\"":
            quote = char
    return False


def forget_assigned(tokens, variables):
    """Unbind each name a command may assign: one it names as a word or as NAME=value.

    export changes only the names it gives a value. source, . and eval may assign any name,
    so they unbind every one.
    """
    if tokens[:1] and tokens[0] in ("source", ".", "eval"):
        variables.clear()
        return
    for token in tokens:
        if tokens[0] != "export" or "=" in token:
            variables.pop(token.split("=", 1)[0], None)


