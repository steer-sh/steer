SEPARATORS = set(";&|()")
WRAPPERS = {"sudo", "env", "time", "nohup", "exec", "command"}
GIT_VALUE_FLAGS = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
PUSH_VALUE_FLAGS = {"--repo", "-o", "--push-option", "--receive-pack", "--exec"}
HEREDOC = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def strip_heredocs(command):
    """Return command without heredoc bodies, which are data."""
    kept = []
    closing = []
    for line in command.split("\n"):
        if closing:
            if line.strip() == closing[0]:
                closing.pop(0)
            continue
        kept.append(line)
        closing.extend(match.group(2) for match in HEREDOC.finditer(line))
    return "\n".join(kept)


