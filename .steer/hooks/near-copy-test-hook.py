#!/usr/bin/env python3
# Steer-Meta: source=generated prompt_version=28 hook_version=28
"""
Hook: block a new Go test whose body nearly copies a test kept in the same file
Rule: never add a Go test that nearly copies another test in the same file | add the case as a row in the twin test or a shared helper, or state in the new test's doc comment what distinct property it checks
Generated by steer
"""

import json
import os
import re
import sys

THRESHOLD = 0.8
SHINGLE = 5
MAX_BYTES = 4 * 1024 * 1024

FUNC = re.compile(r"^func (Test\w*)\(\w+ \*testing\.T\) \{\n(.*?)^\}", re.S | re.M)
OPEN = re.compile(r"^func (Test\w*)\(\w+ \*testing\.T\) \{\n(.*)\Z", re.S | re.M)
HEADER = re.compile(r"^[ \t]*func (Test\w*)\(\w+ \*testing\.T\)", re.M)
TOKEN = re.compile(r'"(?:\\.|[^"\\\n])*"|`[^`]*`|[A-Za-z_]\w*|\d+|\S')
LITERAL = re.compile(r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|//[^\n]*|`[^`]*`|/\*.*?\*/', re.S)


def emptied(m):
    """A raw string or block comment emptied; any other literal unchanged."""
    text = m.group(0)
    if text.startswith("`"):
        return "``"
    if text.startswith("/*"):
        return "/**/"
    return text


def tests(src, open_tail=False):
    """Map each top-level `func TestX(t *testing.T)` name in src to its body.

    Raw strings and block comments are emptied first, so a `}` or `func Test`
    line inside one is not code. With open_tail, a last test left unclosed
    takes the rest of src as its body.
    """
    src = LITERAL.sub(emptied, src)
    found, end = {}, 0
    for m in FUNC.finditer(src):
        found[m.group(1)] = m.group(2)
        end = m.end()
    if open_tail:
        m = OPEN.search(src, end)
        if m and m.group(1) not in found:
            found[m.group(1)] = m.group(2)
    return found


def shingles(body):
    """Token 5-shingles of a body; each string literal is S, each number N."""
    toks = []
    for tok in TOKEN.findall(body):
        toks.append("S" if tok[0] in "\"`" else "N" if tok[0].isdigit() else tok)
    return {tuple(toks[i:i + SHINGLE]) for i in range(max(1, len(toks) - SHINGLE + 1))}


def jaccard(a, b):
    return len(a & b) / len(a | b) if a and b else 0.0


def read(path):
    """The file's text, '' when absent; None when it cannot be read."""
    try:
        if not os.path.exists(path):
            return ""
        if os.path.getsize(path) > MAX_BYTES:
            return None
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except Exception:
        return None


def added_and_kept(tool_name, tool_input, disk):
    """(added, removed, kept) test bodies by name for this edit."""
    before = tests(disk)
    if tool_name == "Write":
        after = tests(tool_input.get("content") or "")
        added = {n: b for n, b in after.items() if n not in before}
        removed = {n: b for n, b in before.items() if n not in after}
        kept = {n: b for n, b in after.items() if n in before}
        return added, removed, kept

    old = tool_input.get("old_string")
    new = tool_input.get("new_string") or ""
    old = old if isinstance(old, str) else ""
    if old and old in disk:
        if tool_input.get("replace_all") is True:
            text = disk.replace(old, new)
        else:
            text = disk.replace(old, new, 1)
        after = tests(text)
        # A patch's fragments can match by chance and land a new test inside
        # another function, so a test whole in new_string counts as well.
        added = {n: b for n, b in tests(new, open_tail=True).items() if n not in before}
        added.update({n: b for n, b in after.items() if n not in before})
        removed = {n: b for n, b in before.items() if n not in after}
        kept = {n: b for n, b in after.items() if n in before}
        return added, removed, kept

    # Fragments that are not one search-and-replace (a patch section, or an
    # old_string the file no longer holds): read headers, not a merged file.
    added = {n: b for n, b in tests(new, open_tail=True).items() if n not in before}
    gone = set(HEADER.findall(old)) - set(HEADER.findall(new))
    removed = {n: b for n, b in before.items() if n in gone}
    kept = {n: b for n, b in before.items() if n not in gone}
    return added, removed, kept


def findings(added, removed, kept):
    """(new, twin, score) for each added test at or above the threshold."""
    kept_sh = {n: shingles(b) for n, b in kept.items()}
    removed_sh = [shingles(b) for b in removed.values()]
    hits = []
    for name, body in sorted(added.items()):
        new = shingles(body)
        best, twin = 0.0, None
        for other, sh in sorted(kept_sh.items()):
            score = jaccard(new, sh)
            if score > best:
                best, twin = score, other
        if twin is None or best < THRESHOLD:
            continue
        # A removed test at least as close is the same test renamed or rewritten.
        if any(jaccard(new, sh) >= best for sh in removed_sh):
            continue
        hits.append((name, twin, best))
    return hits


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except Exception:
        sys.exit(0)

    try:
        tool_name = data.get("tool_name", "")
        tool_input = data.get("tool_input") or {}
        if tool_name not in ("Edit", "Write") or not isinstance(tool_input, dict):
            sys.exit(0)
        if tool_input.get("steer_operation") == "delete":
            sys.exit(0)
        file_path = tool_input.get("file_path", "")
        if not isinstance(file_path, str) or not file_path.endswith("_test.go"):
            sys.exit(0)
        new_text = tool_input.get("new_string") or tool_input.get("content") or ""
        if not isinstance(new_text, str) or "*testing.T)" not in new_text:
            sys.exit(0)

        cwd = data.get("cwd")
        cwd = cwd if isinstance(cwd, str) and cwd else os.getcwd()
        path = file_path if os.path.isabs(file_path) else os.path.join(cwd, file_path)
        disk = read(path)
        if disk is None:
            sys.exit(0)

        hits = findings(*added_and_kept(tool_name, tool_input, disk))
    except Exception:
        sys.exit(0)
    if not hits:
        sys.exit(0)

    pairs = "; ".join(f"{new} nearly copies {twin} (Jaccard {score:.2f})" for new, twin, score in hits)
    reason = (
        f"New test near-copies a test already in {os.path.basename(file_path)}: {pairs}. "
        "Either (a) fold the case into the twin as a table row or a shared helper, "
        "or (b) keep the new test and state in its doc comment what distinct property "
        "it checks that the twin does not. "
        "This guard blocks once per file per session: your next edit to this file will go through."
    )
    print(json.dumps({"decision": "block", "continue": True, "stopReason": reason}))
    sys.exit(0)


if __name__ == "__main__":
    main()
