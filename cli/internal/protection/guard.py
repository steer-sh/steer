#!/usr/bin/env python3
"""
Hook: Steer self-protection
Rule: Block an agent from changing Steer's own state, settings and hook registrations
Generated by steer

Best-effort and lexical: it reads the command text and edited paths, so it stops
a careless agent, not one that hides a write behind bash -c, an interpreter,
eval or a variable.

Steer's own files are closed to every change. A harness configuration file is
open to the Edit and Write tools except where the change removes a Steer entry or
turns hooks off; a shell write to one is blocked, since its result cannot be read.
"""

import collections
import json
import os
import re
import shlex
import sys

SELF_NAME = "steer-self-protection"
SETTING_KEY = "protection.self"

# Value-taking flags of steer's root, remove, register, preset and config
# commands, each long form beside its shorthand. A flag its command does not define makes the CLI exit, so one table
# serves every position in an invocation.
STEER_VALUE_FLAGS = {
    "-C",
    "--directory",
    "--fixtures",
    "--harness",
    "--hook-version",
    "--model",
    "--prompt-modules",
    "--prompt-version",
    "--reason",
    "--rule",
    "--scope",
    "--self-test",
    "--skill-version",
    "--source",
}

STORE_FILES = ("steer-hooks.py", "steer-manifest.json", "steer-audit.jsonl")


def canonicalize_path(path_value, base):
    if not path_value:
        return ""
    expanded = os.path.expanduser(str(path_value).strip())
    if not expanded:
        return ""
    if not os.path.isabs(expanded):
        expanded = os.path.join(base, expanded)
    return os.path.realpath(expanded)


def repo_root(cwd):
    """The directory holding .git above cwd, or cwd itself outside a repository."""
    path = os.path.abspath(cwd)
    while True:
        marker = os.path.join(path, ".git")
        if os.path.isdir(marker) or os.path.isfile(marker):
            return path
        parent = os.path.dirname(path)
        if parent == path:
            return os.path.abspath(cwd)
        path = parent


def codex_home():
    configured = os.environ.get("CODEX_HOME", "").strip()
    if configured:
        return configured
    return os.path.join(os.path.expanduser("~"), ".codex")


# Kinds of harness configuration file.
CLAUDE_SETTINGS = "claude-settings"
CODEX_HOOKS = "codex-hooks"
CODEX_CONFIG = "codex-config"

# The steer command a user runs in place of each kind of Steer file.
STEER_FILE_COMMANDS = {
    "steer-hooks.py": "steer hooks rebuild",
    "steer-manifest.json": "steer register or steer remove",
    "steer-audit.jsonl": "steer audit",
    "config.json": "steer config set",
    "steer-team.lock.json": "steer team lock",
    SELF_NAME + ".py": "steer config set " + SETTING_KEY + " off",
}


def protected_paths(store_dir, cwd):
    """Every file this guard protects, as canonical full path -> ("steer", command)
    for Steer's own files or ("harness", kind) for a harness configuration file."""
    home = os.path.expanduser("~")
    steer_files = [os.path.join(store_dir, name) for name in STORE_FILES]
    steer_files.append(os.path.join(store_dir, SELF_NAME + ".py"))
    steer_files.append(os.path.join(home, ".steer", "config.json"))
    root = repo_root(cwd)
    for store in (os.path.join(root, ".steer", "hooks"), os.path.join(root, ".claude", "hooks")):
        steer_files.extend(os.path.join(store, name) for name in STORE_FILES)
    steer_files.append(os.path.join(root, "steer-team.lock.json"))

    codex = codex_home()
    harness_files = [
        (os.path.join(home, ".claude", "settings.json"), CLAUDE_SETTINGS),
        (os.path.join(root, ".claude", "settings.json"), CLAUDE_SETTINGS),
        (os.path.join(root, ".claude", "settings.local.json"), CLAUDE_SETTINGS),
        (os.path.join(codex, "hooks.json"), CODEX_HOOKS),
        (os.path.join(root, ".codex", "hooks.json"), CODEX_HOOKS),
        (os.path.join(codex, "config.toml"), CODEX_CONFIG),
    ]
    protected = {}
    for path, kind in harness_files:
        protected[canonicalize_path(path, cwd)] = ("harness", kind)
    for path in steer_files:
        protected[canonicalize_path(path, cwd)] = ("steer", STEER_FILE_COMMANDS[os.path.basename(path)])
    return protected


# ---- Steer's entries in a harness configuration file ----

STABLE_EXECUTABLE = os.path.join(os.path.expanduser("~"), ".steer", "bin", "steer")


def is_steer_command(command):
    """Whether a registered hook command is one Steer writes: it runs the guard
    runner steer-hooks.py, or its first word is a steer executable."""
    if not isinstance(command, str):
        return False
    if "steer-hooks.py" in command or STABLE_EXECUTABLE in command or "~/.steer/bin/steer" in command:
        return True
    try:
        words = shlex.split(command)
    except ValueError:
        words = command.split()
    return bool(words) and is_steer_binary(words[0])


def json_commands(value, path=(), matcher=None):
    """Every string under a "command" key, at any depth, as (keys above it, the
    nearest enclosing matcher, its handler's type, command): where it sits decides
    when and whether it runs."""
    found = []
    if isinstance(value, dict):
        if isinstance(value.get("matcher"), str):
            matcher = value["matcher"]
        for key, item in value.items():
            if key == "command" and isinstance(item, str):
                found.append((path, matcher, value.get("type"), item))
            else:
                found.extend(json_commands(item, path + (key,), matcher))
    elif isinstance(value, list):
        for item in value:
            found.extend(json_commands(item, path, matcher))
    return found


COMMAND_FIELD = re.compile(r'"command"\s*:\s*"((?:[^"\\]|\\.)*)"')


def text_commands(text):
    """The "command" fields of text read without parsing it."""
    commands = []
    for match in COMMAND_FIELD.finditer(text):
        try:
            commands.append(json.loads('"' + match.group(1) + '"'))
        except Exception:
            commands.append(match.group(1))
    return commands


def removed_registration(before, after):
    """Whether after registers fewer of Steer's hooks than before: a Steer command
    gone, or moved to another event, matcher or field, counted per occurrence. When
    either side is not JSON both are read for their "command" fields as text."""
    try:
        old = [entry for entry in json_commands(json.loads(before)) if is_steer_command(entry[-1])]
        new = [entry for entry in json_commands(json.loads(after)) if is_steer_command(entry[-1])]
    except Exception:
        old = [command for command in text_commands(before) if is_steer_command(command)]
        new = [command for command in text_commands(after) if is_steer_command(command)]
    return bool(collections.Counter(old) - collections.Counter(new))


DISABLE_ALL_HOOKS = re.compile(r'"disableAllHooks"\s*:\s*true')


def disables_all_hooks(text):
    try:
        parsed = json.loads(text)
        return isinstance(parsed, dict) and parsed.get("disableAllHooks") is True
    except Exception:
        return bool(DISABLE_ALL_HOOKS.search(text))


TOML_HEADER = re.compile(r'^\s*\[\s*([^\]]+?)\s*\]\s*(#.*)?$')
TOML_PAIR = re.compile(r'^\s*([A-Za-z0-9_.\-"' + "'" + r']+)\s*=\s*(.*?)\s*(#.*)?$')


def bare(name):
    """A table or key name with the quotes around each dotted part removed."""
    return ".".join(part.strip().strip("\"'") for part in name.split("."))


def toml_tables(text):
    """A shallow reading of config.toml: table name -> {key: raw value}. Dotted keys
    at the top level land in the table their prefix names."""
    tables = {"": {}}
    current = ""
    for line in text.splitlines():
        header = TOML_HEADER.match(line)
        if header and not line.strip().startswith("[["):
            current = header.group(1)
            tables.setdefault(current, {})
            continue
        pair = TOML_PAIR.match(line)
        if not pair:
            continue
        key, value = pair.group(1).strip('"'), pair.group(2)
        table = current
        if "." in key and current == "":
            table, key = key.rsplit(".", 1)
            tables.setdefault(table, {})
        tables[table][key] = value
    return tables


HOOKS_FALSE = re.compile(r'(^|[\s{,"])(codex_)?hooks"?\s*=\s*false')


def hooks_turned_off(tables):
    """Whether [features] turns hooks off, in a table, a quoted table, dotted keys or
    an inline table."""
    for name, pairs in tables.items():
        if name.startswith(STATE_PREFIX) or bare(name) != "features":
            continue
        for key, value in pairs.items():
            if bare(key) in ("hooks", "codex_hooks") and value.lower() == "false":
                return True
    for key, value in tables.get("", {}).items():
        if bare(key) == "features" and HOOKS_FALSE.search(value.replace("'", '"')):
            return True
    return False


STATE_PREFIX = 'hooks.state."'


def approval_records(tables):
    """config.toml's hook approval sections: key -> (trusted_hash, enabled)."""
    records = {}
    for name, pairs in tables.items():
        if name.startswith(STATE_PREFIX) and name.endswith('"'):
            key = name[len(STATE_PREFIX):-1]
            records[key] = (pairs.get("trusted_hash", ""), pairs.get("enabled", "").lower() != "false")
    return records


def snake_to_event(name):
    return "".join(part.capitalize() for part in name.split("_"))


def approves_steer(key):
    """Whether an approval key names a handler of Steer's. The key is the hooks.json
    path, the event, and the entry and handler indexes; a key Steer cannot resolve
    counts as Steer's."""
    try:
        path, event, entry, handler = key.rsplit(":", 3)
        with open(path, "r", encoding="utf-8") as hooks_file:
            hooks = json.load(hooks_file).get("hooks", {})
        command = hooks[snake_to_event(event)][int(entry)]["hooks"][int(handler)]["command"]
    except Exception:
        return True
    return is_steer_command(command)


def config_change_reason(before, after):
    """Why a config.toml change turns Steer's hooks off, or ""."""
    old_tables, new_tables = toml_tables(before), toml_tables(after)
    if hooks_turned_off(new_tables) and not hooks_turned_off(old_tables):
        return "it turns Codex hooks off"
    old_records, new_records = approval_records(old_tables), approval_records(new_tables)
    for key, (trusted, enabled) in old_records.items():
        if not approves_steer(key):
            continue
        new = new_records.get(key)
        if trusted and (new is None or new[0] != trusted):
            return "it removes Codex's approval of a Steer hook"
        if enabled and new is not None and not new[1]:
            return "it disables a Steer hook"
    for key, (_, enabled) in new_records.items():
        if not enabled and key not in old_records and approves_steer(key):
            return "it disables a Steer hook"
    return ""


def harness_change_reason(kind, before, after):
    """Why turning before into after removes a Steer entry or turns hooks off, or ""."""
    if kind == CODEX_CONFIG:
        return config_change_reason(before, after)
    if removed_registration(before, after):
        return "it removes or moves a hook Steer registered"
    if kind == CLAUDE_SETTINGS and disables_all_hooks(after) and not disables_all_hooks(before):
        return "it sets disableAllHooks"
    return ""


def read_text(path):
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return handle.read()
    except Exception:
        return ""


CONFIG_FRAGMENT = re.compile(r'(codex_)?hooks"?\s*=\s*false|enabled"?\s*=\s*false')


def edit_fragment_reason(kind, old_string, new_string):
    """The fragment check for an Edit whose old text is not in the file, such as a
    patch hunk's lines out of their context. A config.toml fragment carries no table
    header, so any approval or hooks switch in it counts."""
    if kind == CODEX_CONFIG:
        if CONFIG_FRAGMENT.search(new_string) or "trusted_hash" in old_string or "hooks.state" in old_string:
            return "it may turn a Steer hook off, and this edit does not show its table"
        return config_change_reason(old_string, new_string)
    marks = {word for word in ("steer-hooks.py", STABLE_EXECUTABLE, "~/.steer/bin/steer") if word in old_string}
    for match in COMMAND_FIELD.finditer(old_string):
        raw = match.group(1)
        try:
            decoded = json.loads('"' + raw + '"')
        except Exception:
            decoded = raw
        if is_steer_command(decoded):
            marks.add(raw)
    for mark in marks:
        if mark not in new_string:
            return "it removes a hook Steer registered"
    if kind == CLAUDE_SETTINGS and DISABLE_ALL_HOOKS.search(new_string) and not DISABLE_ALL_HOOKS.search(old_string):
        return "it sets disableAllHooks"
    return ""


def harness_edit_reason(kind, path, tool_name, tool_input):
    """Why an Edit or Write of a harness configuration file removes a Steer entry
    or turns hooks off, or ""."""
    before = read_text(path)
    if tool_name == "Write":
        content = tool_input.get("content", "")
        return harness_change_reason(kind, before, content if isinstance(content, str) else "")
    if tool_input.get("steer_operation") == "delete":
        return "it deletes the file"
    old_string = tool_input.get("old_string", "")
    new_string = tool_input.get("new_string", "")
    if not isinstance(old_string, str) or not isinstance(new_string, str):
        return ""
    if old_string and old_string in before:
        if tool_input.get("replace_all") is True:
            after = before.replace(old_string, new_string)
        else:
            after = before.replace(old_string, new_string, 1)
        return harness_change_reason(kind, before, after)
    return edit_fragment_reason(kind, old_string, new_string)


def is_steer_binary(token):
    if not token:
        return False
    return os.path.basename(token).lower() in ("steer", "steer.exe")


def names_self(identifier, self_path, cwd):
    cleaned = str(identifier).strip()
    if not cleaned:
        return False
    base = os.path.basename(cleaned)
    stem = base[:-3] if base.endswith(".py") else base
    if stem == SELF_NAME:
        return True
    return canonicalize_path(cleaned, cwd) == self_path


def command_words(command_text):
    """Split a command into words; each run of unquoted shell punctuation is its own word."""
    lexer = shlex.shlex(command_text, posix=True, punctuation_chars=True)
    lexer.whitespace_split = True
    lexer.commenters = ""
    try:
        return list(lexer)
    except ValueError:
        return re.findall(r"[;&|()<>]+|[^\s;&|()<>]+", command_text)


def is_shell_punctuation(word):
    return bool(word) and set(word) <= set(";&|()<>")


def is_redirection(word):
    return is_shell_punctuation(word) and ("<" in word or ">" in word)


def skip_redirections(words, idx):
    while idx < len(words):
        if is_redirection(words[idx]):
            idx += 2
        elif words[idx].isdigit() and idx + 1 < len(words) and is_redirection(words[idx + 1]):
            idx += 3
        else:
            break
    return idx


# The root flag that runs steer as if it started in another directory.
WORKDIR_FLAGS = ("-C", "--directory")


def attached_workdir(word):
    """The directory a -C or --directory word carries in itself, or None."""
    if word.startswith("--directory="):
        return word[len("--directory="):]
    if word.startswith("-C") and not word.startswith("--") and len(word) > 2:
        return word[3:] if word[2] == "=" else word[2:]
    return None


def steer_positionals(words, start, value_after_redirection):
    """Return the positional arguments of the steer invocation whose arguments begin
    at words[start], and the directory its last -C flag names, "" for none.

    value_after_redirection selects how a value flag followed by a redirection
    reads: the flag's value is the word after the redirection, or the next word.
    Lexing cannot tell these apart, since it loses quotes and adjacency.
    """
    positionals = []
    workdir = ""
    idx = skip_redirections(words, start)
    while idx < len(words):
        word = words[idx]
        if word in STEER_VALUE_FLAGS:
            idx += 1
            if value_after_redirection:
                idx = skip_redirections(words, idx)
            if word in WORKDIR_FLAGS and idx < len(words):
                workdir = words[idx]
            idx += 1
        elif is_shell_punctuation(word):
            break
        elif word.startswith("-"):
            attached = attached_workdir(word)
            if attached is not None:
                workdir = attached
            idx += 1
        else:
            positionals.append(word)
            idx += 1
        idx = skip_redirections(words, idx)
    return positionals, workdir


# Commands that write every file they name, and ones that write only the last.
WRITES_EVERY_OPERAND = {"rm", "rmdir", "unlink", "mv", "chmod", "chown", "truncate", "touch", "tee"}
WRITES_LAST_OPERAND = {"cp", "install", "ln"}
# Commands that take a directory's contents with it.
REMOVES_TREES = {"rm", "rmdir", "mv"}
# Words that run the command after them.
COMMAND_PREFIXES = {"sudo", "command", "env", "nohup", "time", "exec", "builtin"}


def scan_words(command_text):
    """Split a command into words that keep their quotes, so a quoted ">" or ";"
    stays an argument; each run of unquoted shell punctuation is its own word."""
    lexer = shlex.shlex(command_text, posix=False, punctuation_chars=True)
    lexer.whitespace_split = True
    lexer.commenters = ""
    try:
        return list(lexer)
    except ValueError:
        return re.findall(r"[;&|()<>]+|[^\s;&|()<>]+", command_text)


def unquote(word):
    if len(word) >= 2 and word[0] == word[-1] and word[0] in "'\"":
        return word[1:-1]
    return word


def command_segments(words):
    """Split scanned words into simple commands at each unquoted separator."""
    segment = []
    for word in words:
        if is_shell_punctuation(word) and not is_redirection(word):
            if segment:
                yield segment
            segment = []
        else:
            segment.append(word)
    if segment:
        yield segment


def written_paths(segment):
    """The paths one simple command writes, and whether it removes trees: its
    output redirections and the operands its command writes. A file it only
    reads is not one of them."""
    paths = []
    operands = []
    idx = 0
    while idx < len(segment):
        word = segment[idx]
        if is_redirection(word):
            if ">" in word and idx + 1 < len(segment):
                paths.append(unquote(segment[idx + 1]))
            idx += 2
            continue
        operands.append(unquote(word))
        idx += 1

    while operands and ("=" in operands[0] and not operands[0].startswith("-")):
        operands = operands[1:]
    while operands and os.path.basename(operands[0]) in COMMAND_PREFIXES:
        operands = operands[1:]
        while operands and (operands[0].startswith("-") or "=" in operands[0]):
            operands = operands[1:]
    if not operands:
        return paths, False

    name = os.path.basename(operands[0])
    args = [arg for arg in operands[1:] if arg and not arg.startswith("-")]
    if name in WRITES_EVERY_OPERAND:
        paths.extend(args)
    elif name in WRITES_LAST_OPERAND and len(args) > 1:
        # A destination directory receives each source under its own name.
        destination = args[-1]
        paths.append(destination)
        paths.extend(os.path.join(destination, os.path.basename(source)) for source in args[:-1])
    elif name == "dd":
        paths.extend(arg[len("of="):] for arg in args if arg.startswith("of="))
    elif name in ("sed", "perl") and any(arg.startswith("-i") for arg in operands[1:]):
        paths.extend(args)
    return paths, name in REMOVES_TREES


def hits_protected(raw_target, removes_trees, protected, cwd):
    """The protected entry writing raw_target writes: the file itself, or, for a
    command that takes a directory's contents, a directory holding one, preferring
    a Steer file. None when it writes none."""
    canonical = canonicalize_path(raw_target, cwd)
    if not canonical:
        return None
    if canonical in protected:
        return protected[canonical]
    if not removes_trees:
        return None
    prefix = canonical.rstrip(os.sep) + os.sep
    held = [entry for path, entry in protected.items() if path.startswith(prefix)]
    held.sort(key=lambda entry: entry[0] != "steer")
    return held[0] if held else None


def block(reason):
    print(json.dumps({"decision": "block", "continue": True, "stopReason": reason}))


STEER_FILE_REASON = (
    "Steer's self-protection blocks changing {path}: it is Steer's own state. "
    "If the change is needed, ask the user to run {command} themselves."
)
HARNESS_SHELL_REASON = (
    "Steer's self-protection blocks a shell write to {path}, which registers your "
    "agent's hooks. Make the change with the Edit or Write tool instead: Steer checks "
    "those edits and allows any that keep its own entries."
)
HARNESS_EDIT_REASON = (
    "Steer's self-protection blocks this change to {path}: {why}. Keep Steer's "
    "entries as they are; if they must change, ask the user to make the change."
)


def file_reason(path, entry):
    if entry[0] == "steer":
        return STEER_FILE_REASON.format(path=path, command=entry[1])
    return HARNESS_SHELL_REASON.format(path=path)


def evaluate_bash_command(command_text, protected, self_path, cwd):
    # The path scan runs before the steer-command reading, so a compound command
    # cannot carry a protected-file write past an allowed steer subcommand.
    for segment in command_segments(scan_words(command_text)):
        targets, removes_trees = written_paths(segment)
        for raw_target in targets:
            entry = hits_protected(raw_target, removes_trees, protected, cwd)
            if entry:
                return file_reason(raw_target, entry)

    words = command_words(command_text)
    for idx, word in enumerate(words):
        if not is_steer_binary(word):
            continue
        for value_after_redirection in (True, False):
            positionals, workdir = steer_positionals(words, idx + 1, value_after_redirection)
            # steer resolves an operand against its -C directory.
            base = canonicalize_path(workdir, cwd) if workdir else cwd
            reason = evaluate_steer_invocation(positionals, self_path, base)
            if reason:
                return reason
    return None


def evaluate_steer_invocation(positionals, self_path, cwd):
    if not positionals:
        return None
    operation = positionals[0]
    operand = positionals[1] if len(positionals) > 1 else ""

    if operation == "config":
        if operand == "set" and len(positionals) > 2 and positionals[2] == SETTING_KEY:
            return "Steer's self-protection blocks changing the " + SETTING_KEY + " setting. Only the user turns it off."
        return None
    if operation in ("remove", "register") and names_self(operand, self_path, cwd):
        return "Steer's self-protection blocks " + operation + " of its own guard. Only the user turns it off."
    if operation == "preset" and operand == "disable" and len(positionals) > 2 and names_self(positionals[2], self_path, cwd):
        return "Steer's self-protection blocks removing its own guard. Only the user turns it off."
    return None


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except Exception:
        sys.exit(0)
    if not isinstance(data, dict):
        sys.exit(0)

    cwd = data.get("cwd")
    if not isinstance(cwd, str) or not cwd:
        cwd = os.getcwd()
    store_dir = os.path.dirname(os.path.realpath(__file__))
    self_path = canonicalize_path(os.path.join(store_dir, SELF_NAME + ".py"), cwd)
    protected = protected_paths(store_dir, cwd)

    tool_name = data.get("tool_name", "")
    tool_input = data.get("tool_input", {})
    if not isinstance(tool_input, dict):
        sys.exit(0)

    if tool_name == "Bash":
        command = tool_input.get("command", "")
        if isinstance(command, str):
            reason = evaluate_bash_command(command, protected, self_path, cwd)
            if reason:
                block(reason)
        sys.exit(0)

    if tool_name in ("Edit", "Write", "MultiEdit"):
        file_path = tool_input.get("file_path", "")
        canonical = canonicalize_path(file_path, cwd) if isinstance(file_path, str) else ""
        entry = protected.get(canonical) if canonical else None
        if entry is None:
            sys.exit(0)
        if entry[0] == "steer":
            block(file_reason(file_path, entry))
            sys.exit(0)
        edits = [tool_input]
        if tool_name == "MultiEdit":
            # The runtime splits a MultiEdit into Edits; a direct run reads each hunk.
            edits = [dict(hunk, file_path=file_path) for hunk in tool_input.get("edits", []) if isinstance(hunk, dict)]
            tool_name = "Edit"
        for edit in edits:
            why = harness_edit_reason(entry[1], canonical, tool_name, edit)
            if why:
                block(HARNESS_EDIT_REASON.format(path=file_path, why=why))
                break
    sys.exit(0)


if __name__ == "__main__":
    main()
