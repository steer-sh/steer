#!/usr/bin/env python3
"""
Hook: Block git dependencies in package.json dependencies
Rule: In package.json, block git dependencies in the main 'dependencies' section
Generated by steer
"""

import json
import sys
import re


GIT_DEP_PATTERNS = [
    r'^git\+https?://',
    r'^git\+ssh://',
    r'^git://',
    r'^github:',
    r'^bitbucket:',
    r'^gitlab:',
    r'\.git$',
    r'\.git#',
    r'^https?://.*\.git$',
    r'^https?://.*\.git#',
    r'^https?://github\.com/.+/.+#',
    r'^https?://github\.com/.+/.+\.git',
]


def is_git_dep(value):
    if not isinstance(value, str):
        return False
    for pattern in GIT_DEP_PATTERNS:
        if re.search(pattern, value):
            return True
    return False


def check_dependencies_json(content_to_check):
    """Parse as JSON and check the 'dependencies' field only."""
    try:
        pkg = json.loads(content_to_check)
    except (json.JSONDecodeError, ValueError):
        return []

    if not isinstance(pkg, dict):
        return []

    deps = pkg.get('dependencies', {})
    if not isinstance(deps, dict):
        return []

    violations = []
    for name, version in deps.items():
        if is_git_dep(version):
            violations.append(f"  {name}: {version}")
    return violations


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ['Edit', 'MultiEdit', 'Write']:
        sys.exit(0)

    file_path = tool_input.get('file_path', '')

    # Only check package.json files
    if not file_path.endswith('package.json'):
        sys.exit(0)

    # For Write tool, check the full content as JSON
    if tool_name == 'Write':
        content = tool_input.get('content', '')
        if not content.strip():
            sys.exit(0)
        violations = check_dependencies_json(content)
        if violations:
            result = {
                "decision": "block",
                "continue": True,
                "stopReason": (
                    "Git dependencies detected in 'dependencies' section of package.json:\n"
                    + "\n".join(violations)
                    + "\n\nSuggestion: Git dependencies should only be used in 'devDependencies' for local tooling."
                )
            }
            print(json.dumps(result))
            sys.exit(0)

    # For Edit tool, check if git dep patterns appear in new_string
    # Since edits are partial, we check for git URL patterns in the new content
    if tool_name == 'Edit':
        new_string = tool_input.get('new_string', '')
        if not new_string.strip():
            sys.exit(0)

        # Check if any line in new_string contains a git dependency pattern
        # We need to be careful: the edit might be in devDependencies, which is allowed.
        # Since we can't always know the surrounding context, we check if the edit
        # text itself contains "devDependencies" — if so, allow it.
        if 'devDependencies' in new_string:
            sys.exit(0)

        # Look for git dep values in the edit content
        found = []
        for line in new_string.split('\n'):
            line_stripped = line.strip().rstrip(',')
            # Match JSON-like entries: "name": "git+https://..."
            m = re.search(r'"[^"]+"\s*:\s*"([^"]+)"', line_stripped)
            if m:
                value = m.group(1)
                if is_git_dep(value):
                    found.append(line.strip())

        if found:
            result = {
                "decision": "block",
                "continue": True,
                "stopReason": (
                    "Git dependencies detected in package.json edit (likely in 'dependencies'):\n"
                    + "\n".join(found)
                    + "\n\nSuggestion: Git dependencies should only be used in 'devDependencies' for local tooling."
                )
            }
            print(json.dumps(result))
            sys.exit(0)

    # For MultiEdit tool
    if tool_name == 'MultiEdit':
        edits = tool_input.get('edits', [])
        all_found = []
        for edit in edits:
            new_string = edit.get('new_string', '')
            if not new_string.strip():
                continue
            if 'devDependencies' in new_string:
                continue
            for line in new_string.split('\n'):
                line_stripped = line.strip().rstrip(',')
                m = re.search(r'"[^"]+"\s*:\s*"([^"]+)"', line_stripped)
                if m:
                    value = m.group(1)
                    if is_git_dep(value):
                        all_found.append(line.strip())

        if all_found:
            result = {
                "decision": "block",
                "continue": True,
                "stopReason": (
                    "Git dependencies detected in package.json edit (likely in 'dependencies'):\n"
                    + "\n".join(all_found)
                    + "\n\nSuggestion: Git dependencies should only be used in 'devDependencies' for local tooling."
                )
            }
            print(json.dumps(result))
            sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
