#!/usr/bin/env python3
"""
Hook: Block process.env enumeration
Rule: Block code that iterates over all process.env variables. Only allow access to specific, named variables.
Generated by steer
"""

import json
import sys
import re


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')

    # Only check JS/TS files
    if not re.search(r'\.(js|jsx|ts|tsx|mjs|cjs)$', file_path):
        sys.exit(0)

    if tool_name == 'MultiEdit':
        edits = tool_input.get('edits', [])
        content_to_check = '\n'.join(e.get('new_string', '') for e in edits)
    else:
        new_string = tool_input.get('new_string', '')
        content = tool_input.get('content', '')
        content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    # Patterns that enumerate ALL env vars (credential harvesting risk)
    enumeration_patterns = [
        r'for\s*\(\s*(?:const|let|var)\s+\w+\s+(?:in|of)\s+process\.env\b',
        r'for\s*\(\s*\w+\s+(?:in|of)\s+process\.env\b',
        r'Object\.keys\s*\(\s*process\.env\s*\)',
        r'Object\.values\s*\(\s*process\.env\s*\)',
        r'Object\.entries\s*\(\s*process\.env\s*\)',
        r'\.\.\.process\.env\b',
        r'JSON\.stringify\s*\(\s*process\.env\s*\)',
        r'\bprocess\.env\b(?!\s*\.\s*\w)(?!\s*\[\s*[\'"])',
    ]

    # Check each non-comment line
    for line in content_to_check.split('\n'):
        stripped = line.strip()
        if stripped.startswith(('//', '#', '/*', '*')):
            continue

        for pattern in enumeration_patterns:
            if re.search(pattern, line):
                # Make sure this isn't a named access like process.env.FOO or process.env['FOO']
                # The last pattern already excludes these, but double-check for the others
                result = {
                    "decision": "block",
                    "continue": True,
                    "stopReason": (
                        "Blocked: Code enumerates all process.env variables, which risks exposing secrets. "
                        "Only access specific, named environment variables instead "
                        "(e.g., process.env.DATABASE_URL or process.env['API_KEY'])."
                    )
                }
                print(json.dumps(result))
                sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
