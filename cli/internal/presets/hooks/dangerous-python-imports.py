#!/usr/bin/env python3
"""
Hook: Block import of 'pickle' or 'shelve' in Python files
Rule: In Python, block the import of 'pickle' or 'shelve'
Generated by steer
"""

import json
import sys
import ast


DANGEROUS_MODULES = {'pickle', 'shelve'}


class DangerousImportVisitor(ast.NodeVisitor):
    def __init__(self):
        self.violations = []

    def visit_Import(self, node):
        for alias in node.names:
            module_root = alias.name.split('.')[0]
            if module_root in DANGEROUS_MODULES:
                self.violations.append((node.lineno, f"import {alias.name}"))
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        if node.module:
            module_root = node.module.split('.')[0]
            if module_root in DANGEROUS_MODULES:
                self.violations.append((node.lineno, f"from {node.module} import ..."))
        self.generic_visit(node)


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')

    # Only check Python files
    if not file_path.endswith('.py'):
        sys.exit(0)

    new_string = tool_input.get('new_string', '')
    content = tool_input.get('content', '')
    content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    try:
        tree = ast.parse(content_to_check)
    except SyntaxError:
        # Could be a partial edit (Edit tool) - fall back to simple check
        # for import statements in the content
        import re
        lines = content_to_check.split('\n')
        violations = []
        for i, line in enumerate(lines, 1):
            stripped = line.strip()
            # Match: import pickle, import shelve, from pickle ..., from shelve ...
            if re.match(r'^(import|from)\s+(pickle|shelve)\b', stripped):
                violations.append((i, stripped))
        if violations:
            details = '; '.join(f"line {ln}: {desc}" for ln, desc in violations)
            result = {
                "decision": "block",
                "continue": True,
                "stopReason": (
                    f"Dangerous import detected: {details}. "
                    "Suggestion: Use safer serialization formats like JSON for data interchange"
                )
            }
            print(json.dumps(result))
            sys.exit(0)
        sys.exit(0)

    visitor = DangerousImportVisitor()
    visitor.visit(tree)

    if visitor.violations:
        details = '; '.join(f"line {ln}: {desc}" for ln, desc in visitor.violations)
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                f"Dangerous import detected: {details}. "
                "Suggestion: Use safer serialization formats like JSON for data interchange"
            )
        }
        print(json.dumps(result))

    sys.exit(0)


if __name__ == "__main__":
    main()
