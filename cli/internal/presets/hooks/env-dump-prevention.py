#!/usr/bin/env python3
"""
Hook: Block direct execution of the 'env' command
Rule: Block the direct execution of the 'env' command, which can expose all environment variables
Generated by steer
"""

import json
import sys
import re


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    # This rule targets the Bash tool (direct command execution)
    # and shell script files written via Edit/Write
    if tool_name == 'Bash':
        content_to_check = tool_input.get('command', '') or ''
        file_path = ''
    elif tool_name in ['Edit', 'MultiEdit', 'Write']:
        file_path = tool_input.get('file_path', '')
        if tool_name == 'MultiEdit':
            edits = tool_input.get('edits', [])
            content_to_check = '\n'.join(e.get('new_string', '') for e in edits)
        else:
            content_to_check = tool_input.get('new_string', '') or tool_input.get('content', '') or ''
        # Only check shell-related files
        shell_extensions = ('.sh', '.bash', '.zsh', '.fish')
        shell_filenames = ('Dockerfile', 'Makefile')
        basename = file_path.rsplit('/', 1)[-1] if file_path else ''
        if not any(file_path.endswith(ext) for ext in shell_extensions) and basename not in shell_filenames:
            sys.exit(0)
    else:
        sys.exit(0)

    if not content_to_check.strip():
        sys.exit(0)

    if has_bare_env_command(content_to_check, tool_name):
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                "Direct execution of the 'env' command is blocked because it exposes all environment variables. "
                "To access a specific variable, use 'echo $VAR_NAME' or 'printenv VAR_NAME' instead. "
                "If you need to set environment variables for a command, use 'VAR=value command' syntax directly."
            )
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


def has_bare_env_command(content, tool_name):
    """Detect standalone 'env' command that dumps all environment variables.

    Allow:
    - env VAR=value command  (setting env vars for a command)
    - /usr/bin/env python3   (shebang / interpreter selection)
    - printenv SPECIFIC_VAR  (accessing a single variable)
    - echo $ENV_VAR          (accessing a single variable)
    - References to 'env' in comments
    - The word 'env' as part of other words (e.g., 'environment', 'envoy')

    Block:
    - env                    (bare, dumps all vars)
    - env | grep             (piping env output)
    - env | less             (viewing env output)
    - /usr/bin/env           (bare, dumps all vars)
    """
    for line in content.splitlines():
        stripped = line.strip()

        # Skip empty lines and comments
        if not stripped or stripped.startswith('#'):
            continue

        # Check for bare 'env' as a command
        # For Bash tool, each line could be a command or part of a pipeline
        # Match: env, env | ..., env > ..., env >> ...
        # But NOT: env VAR=val cmd, /usr/bin/env python, envsubst, etc.

        # Pattern 1: Line starts with 'env' as standalone command
        if re.match(r'^env\s*$', stripped):
            return True

        # Pattern 2: 'env' piped to something (env | grep, env | less, etc.)
        if re.match(r'^env\s*\|', stripped):
            return True

        # Pattern 3: 'env' with output redirection (env > file, env >> file)
        if re.match(r'^env\s*>{1,2}', stripped):
            return True

        # Pattern 4: 'env' preceded by pipe or semicolon in a compound command
        # e.g., "echo hello; env" or "something | env"
        # Look for env as a standalone segment in pipelines/chains
        # Split by pipe and semicolons, check each segment
        segments = re.split(r'[|;]', stripped)
        for segment in segments[1:]:  # skip first segment (already checked above if it starts with env)
            seg = segment.strip()
            if re.match(r'^env\s*$', seg):
                return True

        # Also check first segment for cases like "sudo env"
        first_seg = segments[0].strip()
        if re.match(r'^sudo\s+env\s*$', first_seg):
            return True

        # Pattern 5: /usr/bin/env with no arguments (bare invocation)
        if re.match(r'^(/usr/bin/env|/bin/env)\s*$', stripped):
            return True
        if re.match(r'^(/usr/bin/env|/bin/env)\s*\|', stripped):
            return True

    return False


if __name__ == "__main__":
    main()
