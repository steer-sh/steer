#!/usr/bin/env python3
"""
Hook: API Key Pattern Detection
Rule: Block strings that look like common API key patterns (e.g., sk_live_, AKIA...)
Generated by steer
"""

import json
import sys
import re


# Patterns that indicate the value is a placeholder/example, not a real secret
SAFE_VALUE_INDICATORS = [
    'your-', 'your_', 'replace', 'example', 'placeholder', 'xxx', 'dummy',
    'fake', 'test_key', 'sample', 'changeme', 'insert', '<your',
]

# Patterns that indicate the key is loaded from a secure source
SECURE_REFERENCE_PATTERNS = [
    r'process\.env\b',
    r'os\.getenv\s*\(',
    r'os\.environ\b',
    r'env\s*\(\s*["\']',
    r'config\.\w+',
    r'settings\.\w+',
    r'secrets\.get',
    r'vault\.',
    r'getenv\s*\(',
    r'System\.getenv\s*\(',
    r'ENV\s*\[',
]

# API key patterns: (description, regex, min_entropy_length)
API_KEY_PATTERNS = [
    # Stripe
    (r'sk_live_[a-zA-Z0-9]{20,}', 'Stripe secret key (sk_live_)'),
    (r'sk_test_[a-zA-Z0-9]{20,}', 'Stripe test key (sk_test_)'),
    (r'pk_live_[a-zA-Z0-9]{20,}', 'Stripe publishable key (pk_live_)'),
    (r'rk_live_[a-zA-Z0-9]{20,}', 'Stripe restricted key (rk_live_)'),
    # AWS
    (r'AKIA[0-9A-Z]{16}', 'AWS Access Key ID (AKIA...)'),
    # Google
    (r'AIza[0-9A-Za-z\-_]{35}', 'Google API key (AIza...)'),
    # Slack
    (r'xoxb-[0-9]{10,}-[0-9a-zA-Z]{20,}', 'Slack bot token (xoxb-)'),
    (r'xoxp-[0-9]{10,}-[0-9a-zA-Z]{20,}', 'Slack user token (xoxp-)'),
    (r'xoxs-[0-9]{10,}-[0-9a-zA-Z]{20,}', 'Slack token (xoxs-)'),
    # GitHub
    (r'ghp_[a-zA-Z0-9]{36}', 'GitHub personal access token (ghp_)'),
    (r'gho_[a-zA-Z0-9]{36}', 'GitHub OAuth token (gho_)'),
    (r'ghu_[a-zA-Z0-9]{36}', 'GitHub user-to-server token (ghu_)'),
    (r'ghs_[a-zA-Z0-9]{36}', 'GitHub server-to-server token (ghs_)'),
    # Twilio
    (r'SK[0-9a-fA-F]{32}', 'Twilio API key (SK...)'),
    # SendGrid
    (r'SG\.[a-zA-Z0-9_\-]{22}\.[a-zA-Z0-9_\-]{43}', 'SendGrid API key (SG.)'),
    # Mailgun
    (r'key-[a-zA-Z0-9]{32}', 'Mailgun API key (key-...)'),
    # Heroku
    (r'[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}', None),
    # OpenAI
    (r'sk-[a-zA-Z0-9]{20}T3BlbkFJ[a-zA-Z0-9]{20}', 'OpenAI API key (sk-...T3BlbkFJ)'),
    # Generic long hex/base64 secrets assigned to suspicious variable names
]

# Variable name patterns that suggest a secret is being assigned
SECRET_VAR_PATTERN = re.compile(
    r'''(?:api[_-]?key|api[_-]?secret|secret[_-]?key|access[_-]?key|auth[_-]?token|'''
    r'''private[_-]?key|password|passwd|credential)\s*[:=]\s*["\'][A-Za-z0-9+/=\-_]{16,}["\']''',
    re.IGNORECASE
)


def line_has_secure_reference(line):
    """Check if the line loads the value from a secure source."""
    for pattern in SECURE_REFERENCE_PATTERNS:
        if re.search(pattern, line):
            return True
    return False


def value_is_placeholder(matched_text):
    """Check if the matched value looks like a placeholder/example."""
    lower = matched_text.lower()
    return any(indicator in lower for indicator in SAFE_VALUE_INDICATORS)


def is_in_comment(line):
    """Check if a line is a comment."""
    stripped = line.strip()
    return stripped.startswith(('#', '//', '/*', '*', '<!--'))


def check_content(content_to_check):
    """Check content for API key patterns. Returns (found, description) or (False, None)."""
    lines = content_to_check.split('\n')

    for line in lines:
        # Skip comments
        if is_in_comment(line):
            continue

        # Skip lines that reference secure sources
        if line_has_secure_reference(line):
            continue

        # Check each API key pattern
        for pattern, description in API_KEY_PATTERNS:
            match = re.search(pattern, line)
            if match and description:  # Skip patterns with None description (too generic)
                matched_text = match.group(0)
                if not value_is_placeholder(matched_text):
                    return True, description

        # Check for secret variable assignments
        match = SECRET_VAR_PATTERN.search(line)
        if match:
            matched_text = match.group(0)
            if not value_is_placeholder(matched_text) and not line_has_secure_reference(line):
                return True, 'Hardcoded secret in variable assignment'

    return False, None


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    # Only check Edit, MultiEdit, Write, and Bash
    if tool_name not in ('Edit', 'MultiEdit', 'Write', 'Bash'):
        sys.exit(0)

    if tool_name == 'Bash':
        content_to_check = tool_input.get('command', '')
    elif tool_name == 'MultiEdit':
        # Check all edits in a MultiEdit
        edits = tool_input.get('edits', [])
        content_to_check = '\n'.join(e.get('new_string', '') for e in edits)
    else:
        new_string = tool_input.get('new_string', '')
        content = tool_input.get('content', '')
        content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    found, description = check_content(content_to_check)
    if found:
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                f"Potential API key or secret detected: {description}. "
                f"Suggestion: Store secrets in environment variables or a secure vault service."
            )
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
