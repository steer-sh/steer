#!/usr/bin/env python3
"""
Hook: Block postinstall scripts in package.json
Rule: In package.json files, never allow a 'postinstall' script. Post-install scripts are a major security risk for supply-chain attacks
Generated by steer
"""

import json
import sys
import re


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')

    # Only check package.json files
    if not file_path.endswith('package.json'):
        sys.exit(0)

    if tool_name == 'MultiEdit':
        edits = tool_input.get('edits', [])
        if not isinstance(edits, list):
            edits = []
        content_to_check = '\n'.join(
            e['new_string'] for e in edits
            if isinstance(e, dict) and isinstance(e.get('new_string'), str)
        )
    else:
        new_string = tool_input.get('new_string', '')
        content = tool_input.get('content', '')
        content_to_check = next(
            (text for text in (new_string, content) if isinstance(text, str) and text),
            ''
        )

    if not content_to_check.strip():
        sys.exit(0)

    # Strategy: check both JSON-parsed and raw text for postinstall
    # JSON parse for Write (full file content), regex for Edit (partial content)
    found = False

    # Try JSON parse first (works for Write tool with full package.json)
    try:
        package_data = json.loads(content_to_check)
    except (ValueError, RecursionError):
        package_data = None
    # Content that decodes to any other shape is left to the raw-text check
    if isinstance(package_data, dict):
        scripts = package_data.get('scripts')
        if isinstance(scripts, dict) and 'postinstall' in scripts:
            found = True

    # Also check raw text for Edit tool (partial content containing postinstall key)
    if not found:
        # Match "postinstall" as a JSON key in scripts context
        if re.search(r'["\']postinstall["\']', content_to_check):
            found = True

    if found:
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                "Blocked: 'postinstall' script detected in package.json. "
                "Post-install scripts are a major security risk for supply-chain attacks. "
                "Remove the 'postinstall' entry from the 'scripts' section."
            )
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
