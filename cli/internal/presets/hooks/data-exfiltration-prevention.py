#!/usr/bin/env python3
"""
Hook: Block piping file-reading commands to network tools
Rule: Block shell commands that pipe the output of a file-reading command (like cat, grep, ls) to a network tool (like curl, wget, nc)
Generated by steer
"""

import json
import sys
import re


# File-reading / data-producing commands
FILE_READ_CMDS = r'(?:cat|head|tail|less|more|grep|egrep|fgrep|rg|ag|ack|find|ls|dir|tree|strings|xxd|od|hexdump|sed|awk|cut|sort|uniq|wc|tee|xargs|tar|zip|gzip|base64|openssl|dd|readlink|realpath|file|stat|diff|comm|join|paste|column|pr|nl|expand|unexpand)'

# Network-capable commands
NETWORK_CMDS = r'(?:curl|wget|nc|ncat|netcat|socat|telnet|ssh|scp|sftp|ftp|rsync|nmap|dig|host|nslookup|sendmail|mail)'

# Pattern: file_reader ... | ... network_tool
# Handles multi-pipe chains: cat foo | base64 | curl ...
PIPE_TO_NETWORK_RE = re.compile(
    r'(?:^|&&|\|\||;)\s*'           # start of command or chained
    + FILE_READ_CMDS +
    r'\b'                            # word boundary after command
    r'[^|&;]*'                       # arguments (no pipe/chain yet)
    r'\|'                            # the pipe
    r'[^&;]*?'                       # optional intermediate pipes
    + NETWORK_CMDS +
    r'\b',
    re.MULTILINE
)

# Also catch: network_tool ... < file  (input redirection from file)
REDIRECT_TO_NETWORK_RE = re.compile(
    r'\b' + NETWORK_CMDS + r'\b[^|&;]*<\s*\S+',
    re.MULTILINE
)

# Also catch: network_tool ... $(file_reader ...)  (command substitution)
SUBSHELL_TO_NETWORK_RE = re.compile(
    r'\b' + NETWORK_CMDS + r'\b[^|&;]*\$\([^)]*\b' + FILE_READ_CMDS + r'\b',
    re.MULTILINE
)

# Reverse: network_tool ... -d @- with stdin from pipe
NETWORK_UPLOAD_RE = re.compile(
    r'(?:^|&&|\|\||;)\s*'
    + FILE_READ_CMDS +
    r'\b[^|&;]*\|\s*'
    + NETWORK_CMDS +
    r'\b',
    re.MULTILINE
)


def check_content(content):
    """Returns a violation message or None."""
    for line in content.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue

        if PIPE_TO_NETWORK_RE.search(stripped):
            return f"Blocked: piping file-reading command output to a network tool: `{stripped.strip()}`"
        if REDIRECT_TO_NETWORK_RE.search(stripped):
            return f"Blocked: redirecting file content into a network tool: `{stripped.strip()}`"
        if SUBSHELL_TO_NETWORK_RE.search(stripped):
            return f"Blocked: using command substitution to feed file data to a network tool: `{stripped.strip()}`"

    return None


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    # Handle both Bash commands and file writes
    if tool_name == 'Bash':
        content_to_check = tool_input.get('command', '') or ''
        file_path = ''
    elif tool_name in ('Edit', 'MultiEdit', 'Write'):
        file_path = tool_input.get('file_path', '')
        if tool_name == 'MultiEdit':
            edits = tool_input.get('edits', [])
            content_to_check = '\n'.join(e.get('new_string', '') for e in edits)
        else:
            content_to_check = tool_input.get('new_string', '') or tool_input.get('content', '') or ''
        # Only check shell-relevant files
        shell_extensions = ('.sh', '.bash', '.zsh', '.fish', '.yml', '.yaml', '.mk')
        basename = file_path.lower().split('/')[-1] if file_path else ''
        if not (any(file_path.lower().endswith(ext) for ext in shell_extensions)
                or basename in ('dockerfile', 'makefile')
                or basename.endswith('.dockerfile')):
            sys.exit(0)
    else:
        sys.exit(0)

    if not content_to_check.strip():
        sys.exit(0)

    violation = check_content(content_to_check)
    if violation:
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": f"{violation}. Piping file contents to network tools risks data exfiltration. Read files and make network requests as separate, intentional steps instead."
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
