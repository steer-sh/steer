#!/usr/bin/env python3
"""
Hook: Protect steer factory hooks and managed files from mutation
Rule: Block mutations to factory-managed hooks and protected steer files in this scope
Generated by steer
"""

import json
import os
import shlex
import sys


def canonicalize_path(path_value):
    if not path_value:
        return ""
    expanded = os.path.expanduser(str(path_value).strip())
    if not expanded:
        return ""
    return os.path.realpath(os.path.abspath(expanded))


def load_manifest(manifest_path):
    try:
        with open(manifest_path, "r", encoding="utf-8") as manifest_file:
            data = manifest_file.read().strip()
        if not data:
            return {}
        parsed = json.loads(data)
        hooks = parsed.get("hooks", {})
        if isinstance(hooks, dict):
            return hooks
    except Exception:
        return {}
    return {}


def collect_factory_targets(hooks_dir, manifest_hooks):
    factory_names = set()
    factory_files = set()
    factory_paths = set()

    for hook_name, entry in manifest_hooks.items():
        if not isinstance(entry, dict):
            continue
        source = str(entry.get("source", "")).strip().lower()
        if source != "factory":
            continue

        normalized_name = str(hook_name).strip()
        if normalized_name:
            factory_names.add(normalized_name)

        file_name = str(entry.get("file", "")).strip()
        if not file_name and normalized_name:
            file_name = normalized_name + ".py"
        if not file_name:
            continue

        factory_files.add(file_name)
        factory_paths.add(canonicalize_path(os.path.join(hooks_dir, file_name)))

    return factory_names, factory_files, factory_paths


def is_steer_binary(token):
    if not token:
        return False
    return os.path.basename(token).lower() in ("steer", "steer.exe")


def find_steer_index(tokens):
    for idx, token in enumerate(tokens):
        if is_steer_binary(token):
            return idx
    return -1


def is_factory_identifier(identifier, factory_names, factory_files, factory_paths):
    cleaned = str(identifier).strip()
    if not cleaned:
        return False

    normalized_name = os.path.basename(cleaned)
    stem = normalized_name[:-3] if normalized_name.endswith(".py") else normalized_name

    if cleaned in factory_names or normalized_name in factory_files or stem in factory_names:
        return True

    canonical = canonicalize_path(cleaned)
    if canonical and canonical in factory_paths:
        return True

    return False


def parse_steer_operation(tokens):
    steer_index = find_steer_index(tokens)
    if steer_index == -1:
        return None, []

    args = tokens[steer_index + 1 :]
    if not args:
        return None, []

    # Skip known global flags.
    consumed = []
    idx = 0
    while idx < len(args):
        token = args[idx]
        consumed.append(token)
        if token == "--scope":
            idx += 2
            continue
        if token.startswith("--scope="):
            idx += 1
            continue
        if token.startswith("-"):
            idx += 1
            continue
        break

    args = args[idx:]
    if not args:
        return None, consumed
    return args[0], args[1:]


def has_flag(args, flag_name):
    for token in args:
        if token == flag_name or token.startswith(flag_name + "="):
            return True
    return False


def first_positional(args):
    for token in args:
        if token.startswith("-"):
            continue
        return token
    return ""


def shell_command_mutates(tokens):
    if not tokens:
        return False

    cmd = tokens[0]
    mutating_commands = {
        "rm",
        "mv",
        "cp",
        "ln",
        "chmod",
        "chown",
        "truncate",
        "install",
        "tee",
        "dd",
        "touch",
    }
    if cmd in mutating_commands:
        return True

    if cmd in ("sed", "perl") and any(token.startswith("-i") for token in tokens[1:]):
        return True

    for token in tokens:
        if token in (">", ">>", "1>", "1>>", "2>", "2>>"):
            return True
        if token.startswith((">", ">>", "1>", "1>>", "2>", "2>>")) and len(token) > 1:
            return True

    return False


def looks_like_target_token(token):
    if not token:
        return False
    if token in {"|", "||", "&", "&&", ";", "(", ")", "{", "}"}:
        return False
    if token.startswith("-"):
        return False
    return True


def referenced_targets(tokens):
    targets = []
    for idx, token in enumerate(tokens):
        if token in (">", ">>", "1>", "1>>", "2>", "2>>"):
            if idx + 1 < len(tokens):
                targets.append(tokens[idx + 1])
            continue

        if token.startswith((">", ">>", "1>", "1>>", "2>", "2>>")) and len(token) > 1:
            split_idx = token.find(">")
            if split_idx != -1:
                target = token[split_idx + 1 :]
                if target:
                    targets.append(target)
            continue

        if looks_like_target_token(token):
            targets.append(token)
    return targets


def matches_protected_target(raw_target, protected_paths, protected_files):
    target = str(raw_target).strip()
    if not target:
        return False

    canonical = canonicalize_path(target)
    if canonical and canonical in protected_paths:
        return True

    base = os.path.basename(target)
    if base in protected_files:
        return True

    return False


def matches_factory_target(raw_target, factory_paths, factory_files):
    target = str(raw_target).strip()
    if not target:
        return False

    canonical = canonicalize_path(target)
    if canonical and canonical in factory_paths:
        return True

    base = os.path.basename(target)
    if base in factory_files:
        return True

    return False


def block(reason):
    print(
        json.dumps(
            {
                "decision": "block",
                "continue": True,
                "stopReason": reason,
            }
        )
    )


def evaluate_bash_command(command_text, factory_names, factory_files, factory_paths, protected_paths, protected_files):
    try:
        tokens = shlex.split(command_text, posix=True)
    except Exception:
        tokens = command_text.split()
    if not tokens:
        return None

    operation, args = parse_steer_operation(tokens)
    if operation == "preset":
        if not args:
            return None
        preset_action = args[0]
        preset_args = args[1:]
        if preset_action == "sync":
            return None
        if preset_action in ("disable", "disable-bundle"):
            return "Blocking factory preset disable operation. Use steer preset sync for reconciliation."
        return None

    if operation == "remove":
        target = first_positional(args)
        if is_factory_identifier(target, factory_names, factory_files, factory_paths):
            return "Blocking removal of a factory-managed hook in this scope."
        return None

    if operation == "register":
        target = first_positional(args)
        if has_flag(args, "--force") and is_factory_identifier(target, factory_names, factory_files, factory_paths):
            return "Blocking force register collision against a factory-managed hook."
        return None

    if not shell_command_mutates(tokens):
        return None

    for raw_target in referenced_targets(tokens):
        if matches_protected_target(raw_target, protected_paths, protected_files):
            return "Blocking mutation of protected steer-managed files in this scope."
        if matches_factory_target(raw_target, factory_paths, factory_files):
            return "Blocking mutation of factory-managed hook files in this scope."

    return None


def evaluate_file_mutation(file_path, factory_paths, protected_paths):
    canonical = canonicalize_path(file_path)
    if not canonical:
        return None
    if canonical in protected_paths:
        return "Blocking mutation of protected steer-managed files in this scope."
    if canonical in factory_paths:
        return "Blocking mutation of factory-managed hook files in this scope."
    return None


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except Exception:
        sys.exit(0)

    hooks_dir = os.path.dirname(os.path.realpath(__file__))
    manifest_path = os.path.join(hooks_dir, "steer-manifest.json")
    settings_path = os.path.join(os.path.dirname(hooks_dir), "settings.json")

    protected_paths = {
        canonicalize_path(os.path.join(hooks_dir, "steer-hooks.py")),
        canonicalize_path(manifest_path),
        canonicalize_path(settings_path),
    }
    protected_files = {"steer-hooks.py", "steer-manifest.json", "settings.json"}

    manifest_hooks = load_manifest(manifest_path)
    factory_names, factory_files, factory_paths = collect_factory_targets(hooks_dir, manifest_hooks)

    tool_name = data.get("tool_name", "")
    tool_input = data.get("tool_input", {})

    if tool_name == "Bash":
        reason = evaluate_bash_command(
            tool_input.get("command", "") or "",
            factory_names,
            factory_files,
            factory_paths,
            protected_paths,
            protected_files,
        )
        if reason:
            block(reason)
        sys.exit(0)

    if tool_name in ("Edit", "Write", "MultiEdit"):
        file_path = tool_input.get("file_path", "")
        reason = evaluate_file_mutation(file_path, factory_paths, protected_paths)
        if reason:
            block(reason)
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
