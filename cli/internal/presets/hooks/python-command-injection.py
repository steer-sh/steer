#!/usr/bin/env python3
"""
Hook: Block command injection in Python files
Rule: In Python files, block command injection vulnerabilities from os.system and subprocess calls with shell=True
Generated by steer
"""

import json
import sys
import ast


class CommandInjectionVisitor(ast.NodeVisitor):
    def __init__(self):
        self.violations = []
        self.has_shlex_import = False
        self.safe_vars = set()

    def visit_Import(self, node):
        for alias in node.names:
            if alias.name == 'shlex':
                self.has_shlex_import = True
        self.generic_visit(node)

    def visit_ImportFrom(self, node):
        if node.module == 'shlex':
            self.has_shlex_import = True
        self.generic_visit(node)

    def visit_Assign(self, node):
        if self.has_shlex_import:
            for target in node.targets:
                if isinstance(target, ast.Name):
                    if self._value_is_shlex_safe(node.value):
                        self.safe_vars.add(target.id)
        self.generic_visit(node)

    def _value_is_shlex_safe(self, node):
        # Direct shlex.quote() call
        if isinstance(node, ast.Call):
            if (isinstance(node.func, ast.Attribute) and
                isinstance(node.func.value, ast.Name) and
                node.func.value.id == 'shlex' and node.func.attr == 'quote'):
                return True
        # f-string when shlex is imported
        if isinstance(node, ast.JoinedStr) and self.has_shlex_import:
            return True
        # List comprehension with shlex.quote inside
        if isinstance(node, ast.ListComp):
            if self._value_is_shlex_safe(node.elt):
                return True
        return False

    def visit_Call(self, node):
        if not isinstance(node.func, ast.Attribute):
            self.generic_visit(node)
            return

        try:
            module_name = node.func.value.id
            func_name = node.func.attr
        except AttributeError:
            self.generic_visit(node)
            return

        # os.system: always uses shell
        if module_name == 'os' and func_name == 'system':
            if node.args and not self._is_static_string(node.args[0]):
                self.violations.append(
                    (node.lineno, "os.system() with dynamic input is a command injection risk")
                )

        # subprocess calls
        if module_name == 'subprocess' and func_name in ('run', 'Popen', 'check_output', 'check_call', 'call'):
            shell_true = any(
                kw.arg == 'shell' and isinstance(kw.value, ast.Constant) and kw.value.value is True
                for kw in node.keywords
            )

            if not shell_true:
                self.generic_visit(node)
                return

            # shell=True found - check the command argument
            if node.args:
                first_arg = node.args[0]
                if not self._is_static_string(first_arg) and not self._uses_shlex_quote(first_arg):
                    self.violations.append(
                        (node.lineno,
                         f"subprocess.{func_name}() with shell=True and dynamic input is a command injection risk")
                    )

        self.generic_visit(node)

    def _is_static_string(self, node):
        return isinstance(node, ast.Constant) and isinstance(node.value, str)

    def _uses_shlex_quote(self, node):
        # Direct shlex.quote() call
        if isinstance(node, ast.Call):
            if (isinstance(node.func, ast.Attribute) and
                isinstance(node.func.value, ast.Name) and
                node.func.value.id == 'shlex' and node.func.attr == 'quote'):
                return True
        # f-string when shlex is imported
        if isinstance(node, ast.JoinedStr) and self.has_shlex_import:
            return True
        # Variable that was previously assigned from a safe source
        if isinstance(node, ast.Name) and node.id in self.safe_vars:
            return True
        return False


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')
    if not file_path.endswith('.py'):
        sys.exit(0)

    new_string = tool_input.get('new_string', '')
    content = tool_input.get('content', '')
    content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    try:
        tree = ast.parse(content_to_check)
    except SyntaxError:
        sys.exit(0)

    visitor = CommandInjectionVisitor()
    visitor.visit(tree)

    if visitor.violations:
        details = "; ".join(f"Line {line}: {msg}" for line, msg in visitor.violations)
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                f"Command injection vulnerability detected: {details}. "
                "Use subprocess with shell=False and pass arguments as a list, "
                "or use shlex.quote() to sanitize dynamic inputs when shell=True is required."
            )
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
