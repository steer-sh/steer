#!/usr/bin/env python3
"""
Hook: Block recursive filesystem searches from home directory
Rule: Block shell commands that use recursive file system tools like 'find' or 'grep -r' starting from the home directory ($HOME)
Generated by steer
"""

import json
import sys
import re
import os


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    # This rule targets Bash commands and shell script files
    if tool_name == 'Bash':
        content_to_check = tool_input.get('command', '') or ''
        file_path = ''
    elif tool_name in ('Edit', 'MultiEdit', 'Write'):
        file_path = tool_input.get('file_path', '')
        content_to_check = tool_input.get('new_string', '') or tool_input.get('content', '') or ''
        # Only check shell-related files
        if file_path:
            shell_extensions = ('.sh', '.bash', '.zsh', '.fish')
            shell_names = ('Makefile', 'Dockerfile')
            basename = os.path.basename(file_path)
            if not any(file_path.endswith(ext) for ext in shell_extensions) and basename not in shell_names:
                sys.exit(0)
    else:
        sys.exit(0)

    if not content_to_check.strip():
        sys.exit(0)

    # Resolve the actual home directory for literal path matching
    home_dir = os.path.expanduser('~')

    # Patterns that represent "starting from home directory"
    # We match: ~, ~/, $HOME, ${HOME}, or the literal home path
    home_ref = r'(?:~/|~\s|(?:\$HOME|\$\{HOME\})(?:/|\s|$)|' + re.escape(home_dir) + r'(?:/|\s|$))'

    # Recursive search tools starting from home:
    # - find <home_ref>
    # - grep -r/-R/--recursive <args> <home_ref>  OR  grep -r <home_ref>
    # - rg <args> <home_ref> (ripgrep is recursive by default)
    # - ag <args> <home_ref> (silver searcher is recursive by default)

    patterns = [
        # find starting from home
        r'\bfind\s+' + home_ref,
        # grep with recursive flag, home ref anywhere after
        r'\bgrep\b[^|&;]*\s+-[a-zA-Z]*[rR][a-zA-Z]*\s+[^|&;]*' + home_ref,
        r'\bgrep\b[^|&;]*--recursive[^|&;]*' + home_ref,
        # home ref before pattern in grep -r
        r'\bgrep\b[^|&;]*' + home_ref + r'[^|&;]*\s+-[a-zA-Z]*[rR]',
        # rg (ripgrep) starting from home
        r'\brg\s+[^|&;]*' + home_ref,
        # ag (silver searcher) starting from home
        r'\bag\s+[^|&;]*' + home_ref,
        # find with home as bare ~ (end of args)
        r'\bfind\s+~\b',
    ]

    def strip_quoted_strings(s):
        """Remove content inside single and double quotes to avoid false positives."""
        # Replace quoted strings with placeholder of same length (spaces)
        result = re.sub(r'"[^"]*"', lambda m: ' ' * len(m.group()), s)
        result = re.sub(r"'[^']*'", lambda m: ' ' * len(m.group()), result)
        return result

    for line in content_to_check.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith('#'):
            continue
        # Strip quoted strings to avoid matching patterns inside echo/printf args
        check_line = strip_quoted_strings(stripped)
        for pattern in patterns:
            if re.search(pattern, check_line):
                result = {
                    "decision": "block",
                    "continue": True,
                    "stopReason": (
                        "Recursive filesystem search starting from the home directory detected. "
                        "This can be extremely slow and resource-intensive. "
                        "Please narrow the search to a specific subdirectory instead of $HOME or ~/."
                    )
                }
                print(json.dumps(result))
                sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
