import json
import sys
import re


def strip_comments_and_strings(code):
    """Remove comments and string literals to avoid false positives."""
    # Remove single-line comments
    code = re.sub(r'//.*?$', '', code, flags=re.MULTILINE)
    # Remove multi-line comments
    code = re.sub(r'/\*.*?\*/', '', code, flags=re.DOTALL)
    # Remove Python single-line comments
    code = re.sub(r'#.*?$', '', code, flags=re.MULTILINE)
    # Remove double-quoted strings
    code = re.sub(r'"[^"]*"', '""', code)
    # Remove single-quoted strings
    code = re.sub(r"'[^']*'", "''", code)
    # Remove template literals
    code = re.sub(r'`[^`]*`', '``', code)
    return code


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')

    if tool_name == 'MultiEdit':
        edits = tool_input.get('edits', [])
        content_to_check = '\n'.join(e.get('new_string', '') for e in edits)
    else:
        new_string = tool_input.get('new_string', '')
        content = tool_input.get('content', '')
        content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    # Only check JS/TS/HTML files and Python files
    relevant_extensions = ('.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs', '.html', '.htm', '.py')
    if not any(file_path.endswith(ext) for ext in relevant_extensions):
        sys.exit(0)

    clean = strip_comments_and_strings(content_to_check)

    # Match eval( as a standalone call — not methods like ast.literal_eval() or JSON.parse()
    # \beval\s*\( matches eval() but not literal_eval(), .eval(), etc.
    # We need to ensure it's not preceded by a dot or underscore (method call or safe variant)
    violations = []
    for match in re.finditer(r'(?<![.\w])eval\s*\(', clean):
        violations.append(match.group().strip())

    if violations:
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                f"Use of eval() detected. eval() is unsafe and can execute arbitrary code. "
                f"Suggestion: use safer alternatives like JSON.parse()"
            )
        }
        print(json.dumps(result))
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
