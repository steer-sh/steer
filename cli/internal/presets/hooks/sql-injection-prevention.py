#!/usr/bin/env python3
"""
Hook: SQL Injection Prevention
Rule: Block SQL queries that use Python f-string or %-formatting for values
Generated by steer
"""

import json
import sys
import ast
import re


SQL_KEYWORDS_RE = re.compile(
    r'\b(SELECT|INSERT|UPDATE|DELETE|DROP|CREATE|ALTER|REPLACE|MERGE|TRUNCATE)\b',
    re.IGNORECASE
)

# Parameterization placeholders indicate values are safely bound
PARAM_PLACEHOLDER_RE = re.compile(r'%s|%\(|:\w+|\?')


class SQLInjectionVisitor(ast.NodeVisitor):
    def __init__(self):
        self.violations = []

    def visit_JoinedStr(self, node):
        """Detect f-strings containing SQL keywords with interpolated values."""
        static_parts = []
        has_dynamic = False
        for value in node.values:
            if isinstance(value, ast.Constant):
                static_parts.append(str(value.value))
            else:
                has_dynamic = True
        if has_dynamic:
            text = ''.join(static_parts)
            if SQL_KEYWORDS_RE.search(text):
                # If the query uses parameterization placeholders for values,
                # the f-string parts are likely table/column names (safe pattern)
                if not PARAM_PLACEHOLDER_RE.search(text):
                    self.violations.append(
                        (node.lineno, "f-string SQL query with interpolated values")
                    )
        self.generic_visit(node)

    def visit_BinOp(self, node):
        """Detect %-formatting with SQL keywords."""
        if isinstance(node.op, ast.Mod) and isinstance(node.left, ast.Constant):
            if isinstance(node.left.value, str):
                if SQL_KEYWORDS_RE.search(node.left.value):
                    self.violations.append(
                        (node.lineno, "%-formatted SQL query with interpolated values")
                    )
        self.generic_visit(node)

    def visit_Call(self, node):
        """Detect 'query'.format(...) with SQL keywords."""
        if (isinstance(node.func, ast.Attribute)
                and node.func.attr == 'format'
                and isinstance(node.func.value, ast.Constant)
                and isinstance(node.func.value.value, str)):
            if SQL_KEYWORDS_RE.search(node.func.value.value):
                self.violations.append(
                    (node.lineno, ".format() SQL query with interpolated values")
                )
        self.generic_visit(node)


def main():
    try:
        stdin_data = sys.stdin.read()
        if not stdin_data.strip():
            sys.exit(0)
        data = json.loads(stdin_data)
    except (json.JSONDecodeError, Exception):
        sys.exit(0)

    tool_name = data.get('tool_name', '')
    tool_input = data.get('tool_input', {})

    if tool_name not in ('Edit', 'MultiEdit', 'Write'):
        sys.exit(0)

    file_path = tool_input.get('file_path', '')
    if not file_path.endswith('.py'):
        sys.exit(0)

    new_string = tool_input.get('new_string', '')
    content = tool_input.get('content', '')
    content_to_check = new_string or content or ''

    if not content_to_check.strip():
        sys.exit(0)

    # Try to parse as Python AST
    try:
        tree = ast.parse(content_to_check)
    except SyntaxError:
        # Partial code from Edit tool - wrap and retry
        try:
            tree = ast.parse("def _():\n" + "\n".join(
                "    " + line for line in content_to_check.splitlines()
            ))
        except SyntaxError:
            sys.exit(0)

    visitor = SQLInjectionVisitor()
    visitor.visit(tree)

    if visitor.violations:
        line, msg = visitor.violations[0]
        result = {
            "decision": "block",
            "continue": True,
            "stopReason": (
                f"SQL injection risk: {msg} (line {line}). "
                "Use parameterized queries to prevent SQL injection vulnerabilities. "
                "Example: cursor.execute(\"SELECT * FROM users WHERE id = %s\", (user_id,))"
            )
        }
        json.dump(result, sys.stdout)
        sys.exit(0)

    sys.exit(0)


if __name__ == "__main__":
    main()
