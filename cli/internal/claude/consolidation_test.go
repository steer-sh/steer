// constantHook mirrors the real-world hook that exposed the consolidation bug:
// a module-level compiled regex referenced from main(). Consolidation used to
// drop the constant, and the master's exception swallowing turned the
// resulting NameError into a silent allow-everything.
const constantHook = `#!/usr/bin/env python3
"""
Hook: block bare python invocations
Rule: never use bare "python" in bash commands | use python3 instead
Generated by steer
"""

import json
import sys
import re

PYTHON_TOKEN_RE = re.compile(
    r'(?<![\w./-])python(?![\w.])'
)

SAFE_NAMES = {"python3", "python3.12"}

def strip_quoted(command):
    return command.replace('"', ' ')

def main():
    try:
        data = json.loads(sys.stdin.read())
    except Exception:
        sys.exit(0)

    if data.get('tool_name', '') != 'Bash':
        sys.exit(0)

    command = data.get('tool_input', {}).get('command', '')
    checkable = strip_quoted(command)
    if PYTHON_TOKEN_RE.search(checkable):
        print(json.dumps({"decision": "block", "continue": True, "stopReason": "use python3"}))
    sys.exit(0)

if __name__ == "__main__":
    main()
`

func consolidateFixture(t *testing.T, hookContent string) string {
	t.Helper()

	dir := t.TempDir()
	origWd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(origWd) })

	hooksDir := filepath.Join(dir, ClaudeDirName, HooksDirName)
	if err := os.MkdirAll(hooksDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(hooksDir, "python3-not-python-hook.py"), []byte(hookContent), 0o755); err != nil {
		t.Fatal(err)
	}

	if err := ConsolidateHooks(ProjectScope); err != nil {
		t.Fatalf("ConsolidateHooks: %v", err)
	}

	master, err := os.ReadFile(filepath.Join(hooksDir, MasterHookName))
	if err != nil {
		t.Fatal(err)
	}
	return string(master)
}

// consolidateWithManifest writes the hook plus a manifest entry keyed by the
// hook stem, then consolidates and returns the master hook source.
func consolidateWithManifest(t *testing.T, hookContent string, entry ManifestEntry) string {
	t.Helper()

	dir := t.TempDir()
	origWd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(origWd) })

	hooksDir := filepath.Join(dir, ClaudeDirName, HooksDirName)
	if err := os.MkdirAll(hooksDir, 0o755); err != nil {
		t.Fatal(err)
	}
	const stem = "python3-not-python-hook"
	if err := os.WriteFile(filepath.Join(hooksDir, stem+".py"), []byte(hookContent), 0o755); err != nil {
		t.Fatal(err)
	}

	if entry.Source != "" {
		m := &Manifest{Hooks: map[string]ManifestEntry{stem: entry}}
		if err := SaveManifest(ProjectScope, m); err != nil {
			t.Fatal(err)
		}
	}

	if err := ConsolidateHooks(ProjectScope); err != nil {
		t.Fatalf("ConsolidateHooks: %v", err)
	}

	master, err := os.ReadFile(filepath.Join(hooksDir, MasterHookName))
	if err != nil {
		t.Fatal(err)
	}
	return string(master)
}

// runMaster executes a master hook source on a blocking input and returns the
// stopReason field of the emitted block reply.
func runMaster(t *testing.T, master string) string {
	t.Helper()

	python, err := exec.LookPath("python3")
	if err != nil {
		t.Skip("python3 not available")
	}

	dir := t.TempDir()
	masterPath := filepath.Join(dir, "master.py")
	if err := os.WriteFile(masterPath, []byte(master), 0o755); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command(python, masterPath)
	cmd.Stdin = strings.NewReader(`{"tool_name":"Bash","tool_input":{"command":"python script.py"}}`)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("master hook errored: %v", err)
	}

	var reply struct {
		StopReason string `json:"stopReason"`
	}
	if err := json.Unmarshal(out, &reply); err != nil {
		t.Fatalf("block reply is not JSON: %q (%v)", out, err)
	}
	return reply.StopReason
}

func TestBlockFooterNamesRemoval(t *testing.T) {
	cases := []struct {
		name  string
		entry ManifestEntry
		want  string
	}{
		{
			name:  "factory preset disables by source_id",
			entry: ManifestEntry{Source: SourceFactory, SourceID: "python3-not-python", Rule: "use python3"},
			want:  "steer preset disable python3-not-python",
		},
		{
			name:  "generated rule removes by hook name",
			entry: ManifestEntry{Source: SourceGenerated, Rule: "use python3"},
			want:  "steer remove python3-not-python-hook",
		},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			reason := runMaster(t, consolidateWithManifest(t, constantHook, tc.entry))
			if !strings.Contains(reason, "use python3") {
				t.Errorf("footer dropped the original reason: %q", reason)
			}
			if !strings.Contains(reason, tc.want) {
				t.Errorf("stopReason missing removal command %q: %q", tc.want, reason)
			}
		})
	}

	t.Run("no manifest entry names the hook only", func(t *testing.T) {
		reason := runMaster(t, consolidateWithManifest(t, constantHook, ManifestEntry{}))
		if !strings.Contains(reason, "python3-not-python-hook") {
			t.Errorf("footer missing hook name: %q", reason)
		}
		if strings.Contains(reason, "steer remove") || strings.Contains(reason, "steer preset disable") {
			t.Errorf("footer printed a removal command with no manifest entry: %q", reason)
		}
	})
}

func TestConsolidationCarriesModuleConstants(t *testing.T) {
	master := consolidateFixture(t, constantHook)

	if !strings.Contains(master, "python3_not_python_hook_PYTHON_TOKEN_RE = re.compile(") {
		t.Error("master hook is missing the prefixed module constant definition")
	}
	if !strings.Contains(master, "python3_not_python_hook_SAFE_NAMES = {") {
		t.Error("master hook is missing the second module constant")
	}
	if !strings.Contains(master, "if python3_not_python_hook_PYTHON_TOKEN_RE.search(checkable):") {
		t.Error("main body does not reference the prefixed constant")
	}
	if strings.Contains(master, "\nPYTHON_TOKEN_RE") {
		t.Error("unprefixed constant leaked into master hook")
	}
	// Docstring content must not be extracted as constants.
	if strings.Contains(master, "Rule: never use") {
		t.Error("docstring content leaked into master hook")
	}
}

func TestConsolidatedMasterBlocksLikeIndividualHook(t *testing.T) {
	python, err := exec.LookPath("python3")
	if err != nil {
		t.Skip("python3 not available")
	}

	master := consolidateFixture(t, constantHook)
	dir := t.TempDir()
	masterPath := filepath.Join(dir, "master.py")
	if err := os.WriteFile(masterPath, []byte(master), 0o755); err != nil {
		t.Fatal(err)
	}

	run := func(input string) string {
		cmd := exec.Command(python, masterPath)
		cmd.Stdin = strings.NewReader(input)
		out, err := cmd.Output()
		if err != nil {
			t.Fatalf("master hook errored: %v", err)
		}
		return string(out)
	}

	blocked := run(`{"tool_name":"Bash","tool_input":{"command":"python script.py"}}`)
	if !strings.Contains(blocked, `"decision": "block"`) {
		t.Errorf("master hook failed to block bare python: %q", blocked)
	}

	allowed := run(`{"tool_name":"Bash","tool_input":{"command":"python3 script.py"}}`)
	if strings.TrimSpace(allowed) != "" {
		t.Errorf("master hook blocked safe command: %q", allowed)
	}
}
